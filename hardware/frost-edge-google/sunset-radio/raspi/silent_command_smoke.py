def read_pi_model():
    try:
        with open("/proc/device-tree/model", "r", encoding="utf-8", errors="ignore") as handle:
            return handle.read().replace("\x00", "").strip()
    except OSError:
        return ""


def is_pi_runtime():
    model = read_pi_model()
    if "Raspberry Pi" in model:
        return True
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    return sys.platform.startswith("linux") and root.startswith("/home/pi/")


def dependency_report(ok, message):
    return {
        "ok": ok,
        "skipped": ok,
        "message": message,
        "host": {
            "platform": sys.platform,
            "piModel": read_pi_model(),
            "wpctl": shutil.which("wpctl") or "",
        },
        "results": [],
    }


def fetch_json(path, timeout=4):
    with urllib.request.urlopen(f"{API_BASE}{path}", timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def post_json(path, payload, timeout=4):
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(
        f"{API_BASE}{path}",
        data=body,
        headers={"content-type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def run(args):
    return subprocess.run(args, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)


def player_processes():
    players = []
    for name in ("ffplay", "cvlc"):
        result = run(["pgrep", "-ax", name])
        players.extend(line for line in result.stdout.splitlines() if line.strip())
    return players


def volume_state():
    return run(["wpctl", "get-volume", "@DEFAULT_AUDIO_SINK@"]).stdout.strip()


def is_silent_state(state):
    volume = volume_state()
    label = str(state.get("label") or "").strip().lower()
    return (
        (label in SILENT_LABELS or label.startswith("静音"))
        and int(state.get("pending") or 0) == 0
        and "MUTED" in volume
        and "0.00" in volume
        and not player_processes()
    )


def restore_ambient_mode(initial_mode):
    if not initial_mode:
        return ""
    current = ambient_mode.load_ambient_mode().get("mode")
    if current != initial_mode:
        ambient_mode.save_ambient_mode(initial_mode)
    return ambient_mode.load_ambient_mode().get("mode")


def wait_for_silent_update(previous_updated_at, timeout):
    deadline = time.monotonic() + timeout
    last_state = {}
    while time.monotonic() < deadline:
        last_state = fetch_json("/api/pi-state").get("state", {})
        if last_state.get("updatedAt") != previous_updated_at and is_silent_state(last_state):
            return True, last_state
        time.sleep(0.2)
    return False, last_state


def main():
    if not shutil.which("wpctl"):
        on_pi = is_pi_runtime()
        print(json.dumps(dependency_report(
            not on_pi,
            "silent_command_smoke 需要 wpctl 验证软静音；本机非 Pi，已安全跳过。" if not on_pi else "Raspberry Pi 上缺少 wpctl，无法验证软静音。",
        ), ensure_ascii=False, indent=2))
        return 0 if not on_pi else 1

    results = []
    ok = True
    initial_ambient_mode = ambient_mode.load_ambient_mode().get("mode")
    restored_ambient_mode = initial_ambient_mode
    try:
        state = fetch_json("/api/pi-state").get("state", {})
        for text, timeout in COMMANDS:
            before_updated_at = state.get("updatedAt")
            started = time.monotonic()
            posted = post_json("/api/pi-control", {"text": text, "source": SMOKE_SOURCE})
            handled, state = wait_for_silent_update(before_updated_at, timeout)
            elapsed_ms = round((time.monotonic() - started) * 1000)
            silent = is_silent_state(state)
            passed = bool(posted.get("ok")) and handled and silent
            ok = ok and passed
            results.append({
                "text": text,
                "source": SMOKE_SOURCE,
                "passed": passed,
                "elapsedMs": elapsed_ms,
                "state": {
                    "label": state.get("label"),
                    "city": state.get("city"),
                    "track": state.get("track"),
                    "message": state.get("message"),
                    "pending": state.get("pending"),
                },
                "volume": volume_state(),
                "players": player_processes(),
            })
    finally:
        restored_ambient_mode = restore_ambient_mode(initial_ambient_mode)
    print(json.dumps({
        "ok": ok,
        "results": results,
        "ambientMode": {
            "initial": initial_ambient_mode,
            "restored": restored_ambient_mode,
        },
    }, ensure_ascii=False, indent=2))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
